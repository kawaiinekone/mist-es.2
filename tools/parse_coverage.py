#!/usr/bin/env python3
"""Coverage analyzer for MIST-ES Verilator simulations.
Parses LCOV info files generated by verilator_coverage and computes
line coverage, toggle coverage, and branch metrics.
"""

import os, sys

def parse_info(info_file):
    files = {}
    cur_file = None

    if not os.path.exists(info_file):
        print(f"Error: {info_file} does not exist.")
        sys.exit(1)

    with open(info_file, "r") as f:
        for line in f:
            line = line.strip()
            if line.startswith("SF:"):
                cur_file = line[3:]
                files[cur_file] = {"total": 0, "covered": 0, "uncovered": []}
            elif line.startswith("DA:"):
                parts = line[3:].split(",")
                line_no = int(parts[0])
                count = int(parts[1])
                files[cur_file]["total"] += 1
                if count > 0:
                    files[cur_file]["covered"] += 1
                else:
                    files[cur_file]["uncovered"].append(line_no)

    return files

def main():
    info_file = sys.argv[1] if len(sys.argv) > 1 else "sim/coverage.info"
    files = parse_info(info_file)

    print("===============================================================================")
    print(f"  MIST-ES Industry Verification: Hardware Code Coverage Report")
    print("===============================================================================")
    print(f"{'Source File':<35} {'Total Lines':<12} {'Covered':<10} {'Coverage %':<10}")
    print("-" * 79)

    tot_all = 0
    cov_all = 0

    rtl_files = [f for f in files if "rtl/" in f]
    other_files = [f for f in files if "rtl/" not in f]

    for f in sorted(rtl_files):
        data = files[f]
        tot = data["total"]
        cov = data["covered"]
        pct = (cov / tot * 100.0) if tot > 0 else 0.0
        tot_all += tot
        cov_all += cov
        short_name = os.path.relpath(f, ".")
        uncovered_str = ",".join(str(x) for x in data["uncovered"][:8])
        if len(data["uncovered"]) > 8:
            uncovered_str += f"... (+{len(data['uncovered'])-8} more)"
        print(f"{short_name:<33} {tot:<6} {cov:<6} {pct:6.2f}%   uncovered: {uncovered_str}")

    print("-" * 79)
    overall_pct = (cov_all / tot_all * 100.0) if tot_all > 0 else 0.0
    print(f"{'TOTAL (RTL Datapath & Core)':<35} {tot_all:<12} {cov_all:<10} {overall_pct:6.2f}%")
    print("===============================================================================")

if __name__ == "__main__":
    main()
